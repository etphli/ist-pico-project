#!/usr/bin/env python3
"""Build, validate and preview the Pip CAD v0.1 model.

Usage (from repo root):  scripts/cad.sh            # everything
                         scripts/cad.sh --no-render
Outputs go to cad/out/ (STL per printable part, assembly STL, PNG previews,
validation_report.md). Requires: manifold3d, numpy, trimesh, matplotlib
(scripts/cad.sh provides them through an ephemeral `uv` environment).
"""

import argparse
import itertools
import json
import math
import sys
import time
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from pip_robot import params  # noqa: E402
from pip_robot.assembly import EXPECTED_CONTACT, PARTS  # noqa: E402

OUT = HERE / "out"
STL = OUT / "stl"

# Common consumer printer beds (for a fit warning only; user said parts may be split)
BEDS = {"220x220x250 (Ender-3 class)": (220, 220, 250), "256x256x256 (Bambu P1/X1 class)": (256, 256, 256),
        "180x180x180 (A1 mini class)": (180, 180, 180)}


def to_arrays(m):
    mesh = m.to_mesh()
    v = np.asarray(mesh.vert_properties)[:, :3].astype(np.float64)
    f = np.asarray(mesh.tri_verts).astype(np.int64)
    return v, f


def centroid_volume(v, f):
    a, b, c = v[f[:, 0]], v[f[:, 1]], v[f[:, 2]]
    vol6 = np.einsum("ij,ij->i", a, np.cross(b, c))
    vol = vol6.sum() / 6.0
    if abs(vol) < 1e-9:
        return np.zeros(3), 0.0
    cen = ((a + b + c) * vol6[:, None]).sum(axis=0) / (24.0 * vol)
    return cen, vol


def write_stl(path, v, f):
    import trimesh
    trimesh.Trimesh(vertices=v, faces=f, process=False).export(path)


def bbox(m):
    b = m.bounding_box()
    return np.array(b[:3]), np.array(b[3:])


def place_for_print(m, rot):
    m = m.rotate(tuple(float(r) for r in rot))
    lo, hi = bbox(m)
    return m.translate((-(lo[0] + hi[0]) / 2, -(lo[1] + hi[1]) / 2, -lo[2]))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-render", action="store_true")
    ap.add_argument("--no-assembly-stl", action="store_true")
    args = ap.parse_args()

    STL.mkdir(parents=True, exist_ok=True)
    t0 = time.time()
    built, report, problems = {}, [], []

    report.append(f"# Pip CAD v{params.VERSION} - automated validation report\n")
    report.append("Generated by `scripts/cad.sh` (cad/build.py). These are GEOMETRY checks on the "
                  "parametric model with PLACEHOLDER dimensions for bought parts. They do not prove "
                  "the real parts fit, print well, or are strong enough. See "
                  "docs/12-measurement-calibration-checklist.md.\n")

    # ---- build every part ----------------------------------------------------
    report.append("## 1. Part build and mesh validity\n")
    report.append("| part | kind | qty | status | manifold genus | volume cm3 | bbox (mm, assembly) | print bbox (mm) |")
    report.append("|---|---|---|---|---|---|---|---|")
    for p in PARTS:
        m = p.make()
        st = str(m.status()).split(".")[-1]
        ok = st == "NoError" and not m.is_empty() and m.volume() > 0
        if not ok:
            problems.append(f"{p.name}: status={st} empty={m.is_empty()} vol={m.volume():.1f}")
        built[p.name] = m
        lo, hi = bbox(m)
        size = hi - lo
        pbb = ""
        if p.kind in ("print", "cal") and ok:
            pm = place_for_print(m, p.print_rot)
            v, f = to_arrays(pm)
            write_stl(STL / f"{p.name}.stl", v, f)
            plo, phi = bbox(pm)
            ps = phi - plo
            pbb = f"{ps[0]:.0f} x {ps[1]:.0f} x {ps[2]:.0f}"
            fits = [k for k, (bx, by, bz) in BEDS.items() if all(a <= b for a, b in zip(sorted(ps[:2]), sorted((bx, by)))) and ps[2] <= bz]
            if not fits:
                problems.append(f"{p.name}: print bbox {pbb} exceeds all reference beds (split or re-orient)")
        report.append(f"| {p.name} | {p.kind} | {p.qty} | {st} | {m.genus()} | {m.volume()/1000:.1f} | "
                      f"{size[0]:.0f} x {size[1]:.0f} x {size[2]:.0f} | {pbb} |")
    report.append("")

    # ---- independent re-check of the exported STL files ----------------------
    import trimesh
    report.append("## 1b. Exported STL re-check (trimesh, independent of manifold3d)\n")
    report.append("| file | triangles | watertight | winding consistent | volume cm3 |")
    report.append("|---|---|---|---|---|")
    for f in sorted(STL.glob("*.stl")):
        tm = trimesh.load(f, force="mesh")
        wt, wc = bool(tm.is_watertight), bool(tm.is_winding_consistent)
        if not (wt and wc):
            problems.append(f"{f.name}: watertight={wt} winding={wc}")
        report.append(f"| {f.name} | {len(tm.faces)} | {wt} | {wc} | {tm.volume/1000:.1f} |")
    report.append("")

    # ---- interference matrix -------------------------------------------------
    report.append("## 2. Interference check (all part pairs, assembled position)\n")
    report.append("Unexpected overlap > 1 mm3 between parts that should not touch is listed as a problem. "
                  "Expected contacts (pegs in sockets, captured parts) are listed separately.\n")
    names = [p.name for p in PARTS if p.kind != "cal"]
    boxes = {n: bbox(built[n]) for n in names}
    unexpected, expected = [], []
    for a, b in itertools.combinations(names, 2):
        (la, ha), (lb, hb) = boxes[a], boxes[b]
        if np.any(ha < lb) or np.any(hb < la):
            continue
        vol = (built[a] ^ built[b]).volume()
        if vol <= 1.0:
            continue
        key = frozenset((a, b))
        (expected if key in EXPECTED_CONTACT else unexpected).append((a, b, vol))
    if unexpected:
        report.append("**Unexpected interference:**\n")
        for a, b, vol in sorted(unexpected, key=lambda t: -t[2]):
            report.append(f"- `{a}` x `{b}`: {vol:.1f} mm3")
            problems.append(f"interference {a} x {b}: {vol:.1f} mm3")
    else:
        report.append("No unexpected interference above the configured threshold found. Excluded contact pairs still require fit review.\n")
    report.append("\nExpected contacts with overlap volume (press fits / pegs / captured):\n")
    for a, b, vol in expected:
        report.append(f"- `{a}` x `{b}`: {vol:.1f} mm3")
    report.append("")

    # ---- clearances that matter for motion / safety --------------------------
    report.append("## 3. Selected clearances (min gap, mm; search radius 10 mm)\n")
    report.append("| pair | why | min gap |")
    report.append("|---|---|---|")
    pairs = [("drive_wheel_L", "base_plate", "tyre vs guard well / plate slot"),
             ("drive_wheel_R", "base_plate", "tyre vs guard well / plate slot"),
             ("caster_fork_F", "base_plate", "caster swivel sweep (only one angle checked)"),
             ("caster_wheel_F", "base_plate", "caster wheel vs tower"),
             ("head_base", "top_deck", "rotating head skirt vs fixed neck"),
             ("head_cap", "front_shell", "head vs body shoulder"),
             ("head_cap", "rear_shell", "head vs body shoulder"),
             ("ref_power_bank", "tray", "bank in tray"),
             ("ref_power_bank", "rear_shell", "bank rear vs charge-port wall"),
             ("ref_robo_pico", "rear_shell", "board components vs shell"),
             ("ref_tt_motor_L", "base_plate", "motor in cradle"),
             ("ref_servo", "top_deck", "servo in neck"),
             ("ref_xiao_cam", "head_cap", "camera behind eye"),
             ("clutch_disc", "head_base", "clutch in pocket")]
    for a, b, why in pairs:
        g = built[a].min_gap(built[b], 10.0)
        report.append(f"| {a} / {b} | {why} | {g:.2f} |")
    report.append("")

    # ---- motion sweeps --------------------------------------------------------
    report.append("## 3b. Sampled motion checks (not a continuous collision proof)\n")
    from manifold3d import Manifold
    from pip_robot import parts as pt
    cx = params.P.caster.x
    for tag, fork, wheel, axle in (("front", "caster_fork_F", "caster_wheel_F", "caster_axle_F"),
                                   ("rear", "caster_fork_R", "caster_wheel_R", "caster_axle_R")):
        sx = cx if tag == "front" else -cx
        mov = built[fork] + built[wheel] + built[axle]
        worst = 0.0
        for ang in range(0, 360, 15):
            r = mov.translate((-sx, 0, 0)).rotate((0, 0, ang)).translate((sx, 0, 0))
            worst = max(worst, (r ^ built["base_plate"]).volume())
        ok = worst <= 1.0
        report.append(f"- {tag} caster swivel 0-345 deg (15 deg steps) vs base_plate: max overlap {worst:.1f} mm3 -> {'OK' if ok else 'COLLISION'}")
        if not ok:
            problems.append(f"{tag} caster swivel collides with base plate ({worst:.1f} mm3)")
    head = built["head_base"] + built["head_cap"] + built["eye_left_camera"] + built["eye_right"] + built["clutch_disc"] + built["ref_xiao_cam"]
    fixed = {"top_deck": built["top_deck"], "front_shell": built["front_shell"], "rear_shell": built["rear_shell"]}
    for ang in (-70, -35, 35, 70):
        r = head.rotate((0, 0, ang))
        for n, f in fixed.items():
            v = (r ^ f).volume()
            if v > 1.0:
                problems.append(f"head at {ang} deg collides with {n} ({v:.1f} mm3)")
            report.append(f"- head pan {ang:+d} deg vs {n}: overlap {v:.1f} mm3")
    report.append("- Stop pin contacts the groove end at +/-75 deg by design (not checked here).\n")

    # ---- mass / centre of gravity / tip angle --------------------------------
    report.append("## 4. Static stability ESTIMATE\n")
    total_m, mom = 0.0, np.zeros(3)
    rows = []
    for p in PARTS:
        if p.kind == "cal":
            continue
        v, f = to_arrays(built[p.name])
        cen, vol = centroid_volume(v, f)
        if p.kind in ("print", "inst"):
            mass = vol / 1000 * params.PLA_DENSITY * params.EFFECTIVE_FILL
            total_m += mass
            mom += mass * cen
    plastics = total_m
    refmap = {"power_bank": "ref_power_bank", "tt_motor_L": "ref_tt_motor_L", "tt_motor_R": "ref_tt_motor_R",
              "fs90_servo": "ref_servo", "robo_pico_with_pico": "ref_robo_pico", "xiao_sense": "ref_xiao_cam",
              "speaker_module": "ref_front_modules", "piicodev_modules_x6": "ref_front_modules"}
    for k, (mass, src) in params.COMPONENT_MASS_G.items():
        if k in refmap:
            v, f = to_arrays(built[refmap[k]])
            cen, _ = centroid_volume(v, f)
        else:
            cen = np.array([0.0, 0.0, 120.0])
        total_m += mass
        mom += mass * cen
        rows.append(f"| {k} | {mass:.0f} | {src} |")
    cg = mom / total_m
    # support polygon: drive wheel contacts (0, +-track/2) + caster contacts (only when rocked)
    yc = params.P.drive.track / 2
    side_tip = math.degrees(math.atan2(yc - abs(cg[1]), cg[2]))
    cx = params.P.caster.x - params.P.caster.trail
    fwd_tip = math.degrees(math.atan2(cx - cg[0], cg[2]))
    back_tip = math.degrees(math.atan2(cx + cg[0], cg[2]))
    report.append(f"- Printed plastic (PLA, {params.EFFECTIVE_FILL:.0%} effective fill): ~{plastics:.0f} g")
    report.append(f"- Estimated total mass: ~{total_m:.0f} g (component masses below are partly guesses)")
    report.append(f"- Estimated CG: x={cg[0]:.1f} y={cg[1]:.1f} z={cg[2]:.1f} mm")
    report.append(f"- Static tip angle sideways (over a drive wheel): ~{side_tip:.0f} deg")
    report.append(f"- Static tip angle forward/back (over a caster, worst trail orientation): ~{fwd_tip:.0f} / {back_tip:.0f} deg")
    report.append("- Physical test required: tilt-table test with the real build (docs/09).\n")
    report.append("| component | mass g | source |\n|---|---|---|")
    report += rows
    report.append("")

    # ---- summary ---------------------------------------------------------------
    report.append("## 5. Summary\n")
    if problems:
        report.append(f"**{len(problems)} problem(s):**\n")
        report += [f"- {p}" for p in problems]
    else:
        report.append("All automated geometry checks passed (this does NOT mean the design is verified on real parts).")
    report.append(f"\nBuild time {time.time()-t0:.0f} s. Placeholder dimensions are marked `# MEASURE` in cad/pip_robot/params.py.")

    # ---- assembly export + previews ------------------------------------------
    if not args.no_assembly_stl:
        vs, fs, off = [], [], 0
        meta = []
        for p in PARTS:
            if p.kind == "cal":
                continue
            v, f = to_arrays(built[p.name])
            vs.append(v)
            fs.append(f + off)
            off += len(v)
            meta.append({"name": p.name, "kind": p.kind, "colour": p.colour})
        write_stl(OUT / "assembly_preview.stl", np.vstack(vs), np.vstack(fs))
        (OUT / "assembly_parts.json").write_text(json.dumps(meta, indent=1))
    (OUT / "validation_report.md").write_text("\n".join(report) + "\n")
    if not args.no_render:
        from render import render_all
        render_all(built, PARTS, OUT)
    print("\n".join(report[-(len(problems) + 4):]))
    print(f"\nWrote {OUT}")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
